"""Firmware for the real robot: a generated ``robot_config.h`` configures the one Talaria sketch for any
spec (``hermes talaria firmware <robot> <out_dir>``).

The sketch (firmware/talaria_robot) enforces its own limits: angles are clamped to each joint's range
and transitions are stretched to each joint's max_speed, the same rule the simulator uses, so a move
plays on the robot at the timing it was checked at.
"""

from __future__ import annotations

import shutil
from pathlib import Path

from .spec import Spec

SKETCH_DIR = Path(__file__).resolve().parent / "firmware" / "talaria_robot"
SKETCH_NAME = "talaria_robot"


def _c_string(text: str) -> str:
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def robot_config_h(spec: Spec) -> str:
    """The C header that describes ``spec`` to the firmware."""
    hw = spec.hardware_mapping()
    ctl = hw["controller"]
    hostname = ctl.get("hostname") or spec.name.replace("_", "-")[:32]
    channels = [j["channel"] for j in hw["joints"]]
    if len(set(channels)) != len(channels):
        raise ValueError("two joints use the same PCA9685 channel; set joint.hardware.channel for each")
    if any(not 0 <= c <= 15 for c in channels):
        raise ValueError("PCA9685 channels must be 0..15")
    if len(channels) > 16:
        raise ValueError("the firmware drives at most 16 servos (one PCA9685)")
    rows = []
    for j in hw["joints"]:
        rows.append(f'  {{{_c_string(j["name"]):18s}, {j["channel"]:2d}, {j["min"]:7.2f}f, {j["max"]:7.2f}f, '
                    f'{j["home"]:7.2f}f, {j["max_speed"]:8.2f}f, {int(round(j["center_us"])):5d}, '
                    f'{j["us_per_deg"]:6.3f}f, {"true " if j["direction"] < 0 else "false"}}},')
    return f"""// Generated by Talaria Bench from the robot spec "{spec.name}" (spec hash {spec.hash()[:16]}).
// Regenerate with `hermes talaria firmware {spec.name} <out_dir>` instead of editing by hand, so the
// robot keeps matching the model its moves were checked against.
#pragma once
#include <stdint.h>

#define ROBOT_NAME      {_c_string(spec.name)}
#define ROBOT_SPEC_HASH {_c_string(spec.hash()[:16])}
#define ROBOT_HOSTNAME  {_c_string(hostname)}

// I2C bus and PCA9685 servo driver
#define I2C_SDA       {int(ctl["sda"])}
#define I2C_SCL       {int(ctl["scl"])}
#define PCA9685_ADDR  0x{int(ctl["pca9685_addr"]):02X}
#define SERVO_FREQ_HZ {int(ctl["servo_freq_hz"])}
#define SERVO_MIN_US  {int(ctl["servo_min_us"])}
#define SERVO_MAX_US  {int(ctl["servo_max_us"])}

// Optional SH1106 128x64 I2C screen on the same bus: shows the robot's address after Wi-Fi connects.
#define HAS_OLED      {1 if int(ctl.get("oled") or 0) else 0}
#define OLED_ADDR     0x{int(ctl.get("oled_addr") or 0x3C):02X}

// One row per servo. Angles are degrees from the neutral pose; the firmware never goes outside
// [min, max] and never turns a joint faster than max_speed (deg/s), whatever it is asked.
struct JointConfig {{
  const char* name;
  uint8_t channel;
  float minDeg;
  float maxDeg;
  float homeDeg;
  float maxSpeed;
  uint16_t centerUs;
  float usPerDeg;
  bool invert;
}};

static const JointConfig JOINTS[] = {{
  //  name                ch      min      max     home    speed  center  us/deg invert
{chr(10).join(rows)}
}};
"""


def export_firmware(spec: Spec, out_dir: Path | str) -> Path:
    """Write the Arduino sketch folder for ``spec`` into ``out_dir/talaria_robot`` and return it."""
    target = Path(out_dir) / SKETCH_NAME
    target.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(SKETCH_DIR / f"{SKETCH_NAME}.ino", target / f"{SKETCH_NAME}.ino")
    shutil.copyfile(SKETCH_DIR / "secrets.example.h", target / "secrets.example.h")
    (target / "robot_config.h").write_text(robot_config_h(spec), encoding="utf-8")
    return target
