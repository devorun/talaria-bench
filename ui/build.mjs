// Builds both UI surfaces from the same source (ui/src):
//   desktop/plugin.js       Hermes Desktop page: ESM, imports only @hermes/plugin-sdk, react, react/jsx-runtime
//   dashboard/dist/index.js web dashboard tab: IIFE, React comes from window.__HERMES_PLUGIN_SDK__
// three.js is bundled into both. Output is not minified so reviewers can read it.
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const banner = '// Talaria Bench UI - generated by ui/build.mjs from ui/src (do not edit by hand).\n' +
  '// Bundles three.js (MIT, https://threejs.org). Simulation results only.\n'

const common = {
  bundle: true,
  minify: false,
  target: 'es2020',
  jsx: 'automatic',
  legalComments: 'none',
  logLevel: 'info',
  charset: 'utf8',
  banner: { js: banner },
  define: { 'process.env.NODE_ENV': '"production"' },
}

await build({
  ...common,
  entryPoints: [path.join(here, 'src/desktop.jsx')],
  outfile: path.join(root, 'desktop/plugin.js'),
  format: 'esm',
  external: ['react', 'react/jsx-runtime', '@hermes/plugin-sdk'],
})

// Dev-only: the gallery renderer used by scripts/render_gallery.py (gitignored, not shipped).
await build({
  ...common,
  entryPoints: [path.join(here, 'src/gallery-render.js')],
  outfile: path.join(here, 'render/render.js'),
  format: 'iife',
})

await build({
  ...common,
  entryPoints: [path.join(here, 'src/dashboard.jsx')],
  outfile: path.join(root, 'dashboard/dist/index.js'),
  format: 'iife',
  alias: {
    react: path.join(here, 'src/shims/react.js'),
    'react/jsx-runtime': path.join(here, 'src/shims/jsx-runtime.js'),
  },
})
